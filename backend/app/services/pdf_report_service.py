    def _build_kpi_grid(self, metrics: List[Dict[str, str]]) -> Table:
        """Create clean grid of KPI cards."""
        num_cards = len(metrics)
        col_width = self.usable_width / num_cards
        card_cells = []

        for m in metrics:
            cell_content = [
                Paragraph(m["label"], self.style_kpi_label),
                Spacer(1, 3),
                Paragraph(m["value"], self.style_kpi_val),
            ]
            if "subtext" in m:
                cell_content.extend([
                    Spacer(1, 2),
                    Paragraph(m["subtext"], ParagraphStyle(
                        "KpiSub", fontName="Helvetica", fontSize=7, leading=8, textColor=self.c_muted
                    )),
                ])
            card_cells.append(cell_content)

        kpi_table = Table([card_cells], colWidths=[col_width] * num_cards)
        kpi_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), self.c_bg_light),
            ("BOX", (0, 0), (-1, -1), 1, self.c_border),
            ("INNERGRID", (0, 0), (-1, -1), 1, self.c_border),
            ("TOPPADDING", (0, 0), (-1, -1), 8),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
            ("LEFTPADDING", (0, 0), (-1, -1), 10),
            ("RIGHTPADDING", (0, 0), (-1, -1), 10),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ]))
        return kpi_table

    def _build_activity_mini_chart(self, summaries: List[Dict[str, Any]]) -> Optional[Drawing]:
        """
        Render a compact, professional SVG-style chart showing Played vs Won when >= 2 data points exist.
        """
        if len(summaries) < 2:
            return None

        # Take up to 12 most recent points in chronological order
        items = list(reversed(summaries[:12]))
        if not items:
            return None

        chart_w = self.usable_width
        chart_h = 100
        d = Drawing(chart_w, chart_h)

        # Background box
        d.add(Rect(0, 0, chart_w, chart_h, fillColor=self.c_bg_light, strokeColor=self.c_border, strokeWidth=1, rx=4, ry=4))

        # Title & Legend
        d.add(String(12, chart_h - 14, "Gameplay Trend (Played vs Won)", fontName="Helvetica-Bold", fontSize=8, fillColor=self.c_primary))
        
        # Legend items
        # Played dot + text
        d.add(Rect(chart_w - 120, chart_h - 15, 7, 7, fillColor=colors.HexColor("#94a3b8"), strokeColor=None))
        d.add(String(chart_w - 110, chart_h - 14, "Played", fontName="Helvetica", fontSize=7, fillColor=self.c_muted))
        # Won dot + text
        d.add(Rect(chart_w - 65, chart_h - 15, 7, 7, fillColor=self.c_success, strokeColor=None))
        d.add(String(chart_w - 55, chart_h - 14, "Won", fontName="Helvetica", fontSize=7, fillColor=self.c_muted))

        # Chart area
        pad_x = 24
        pad_y_bottom = 20
        pad_y_top = 26
        usable_cw = chart_w - (pad_x * 2)
        usable_ch = chart_h - pad_y_bottom - pad_y_top

        max_val = max(max(s.get("total_games", 0) for s in items), 5)
        group_w = usable_cw / len(items)
        bar_w = min(12, group_w * 0.35)

        # Baseline
        d.add(Line(pad_x, pad_y_bottom, chart_w - pad_x, pad_y_bottom, strokeColor=self.c_border, strokeWidth=1))

        for idx, item in enumerate(items):
            center_x = pad_x + idx * group_w + (group_w / 2)
            tot = item.get("total_games", 0)
            won = item.get("games_won", 0)

            tot_h = (tot / max_val) * usable_ch if max_val > 0 else 0
            won_h = (won / max_val) * usable_ch if max_val > 0 else 0

            # Played bar
            d.add(Rect(center_x - bar_w - 1, pad_y_bottom, bar_w, max(1, tot_h), fillColor=colors.HexColor("#cbd5e1"), strokeColor=None))
            # Won bar
            d.add(Rect(center_x + 1, pad_y_bottom, bar_w, max(1, won_h), fillColor=self.c_success, strokeColor=None))

            # Date label
            d_val = item.get("date")
            d_str = d_val.strftime("%d %b") if isinstance(d_val, (date, datetime)) else str(d_val)[:6]
            d.add(String(center_x, pad_y_bottom - 10, d_str, fontName="Helvetica", fontSize=6.5, fillColor=self.c_muted, textAnchor="middle"))

        return d

    def generate_daily_report_pdf(
        self,
        summaries: List[Dict[str, Any]],
        start_date: Optional[date] = None,
        end_date: Optional[date] = None,
        target_date: Optional[date] = None,
    ) -> io.BytesIO:
        """Generate official Daily Activity Report PDF document."""
        buffer = io.BytesIO()
        doc = SimpleDocTemplate(
            buffer,
            pagesize=A4,
            leftMargin=self.margin,
            rightMargin=self.margin,
            topMargin=self.margin,
            bottomMargin=self.margin + 12,
        )

        elements: List[Any] = []
        period_str = self._format_period(start_date, end_date, target_date)

        # 1. Header
        elements.extend(self._build_header("Daily Activity Report", period_str))

        # 2. Executive Summary Metrics
        tot_players = sum(s.get("number_of_users", 0) for s in summaries)
        tot_games = sum(s.get("total_games", 0) for s in summaries)
        tot_won = sum(s.get("games_won", 0) for s in summaries)
        win_rate = (tot_won / tot_games * 100.0) if tot_games > 0 else 0.0

        metrics = [
            {"label": "Active Players", "value": str(tot_players)},
            {"label": "Games Played", "value": str(tot_games)},
            {"label": "Correct Guesses", "value": str(tot_won)},
            {"label": "Win Rate", "value": f"{win_rate:.1f}%"},
        ]

        elements.append(Paragraph("Activity Summary", self.style_section_title))
        elements.append(self._build_kpi_grid(metrics))
        elements.append(Spacer(1, 10))

        # 3. Optional Visual Summary Chart
        chart = self._build_activity_mini_chart(summaries)
        if chart:
            elements.append(chart)
            elements.append(Spacer(1, 12))

        # 4. Daily Breakdown Table
        elements.append(Paragraph("Daily Breakdown", self.style_section_title))

        if not summaries:
            empty_table = Table([[Paragraph("No gameplay records found for the selected reporting period.", self.style_empty)]], colWidths=[self.usable_width])
            empty_table.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, -1), self.c_bg_light),
                ("BOX", (0, 0), (-1, -1), 1, self.c_border),
                ("TOPPADDING", (0, 0), (-1, -1), 16),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 16),
            ]))
            elements.append(empty_table)
        else:
            # Table Header
            table_data = [[
                Paragraph("Date", self.style_th),
                Paragraph("Active Players", self.style_th_right),
                Paragraph("Games Played", self.style_th_right),
                Paragraph("Correct Guesses", self.style_th_right),
                Paragraph("Win Rate", self.style_th_right),
            ]]

            # Rows
            for idx, s in enumerate(summaries):
                d_val = s.get("date")
                d_str = d_val.strftime("%d %b %Y") if isinstance(d_val, (date, datetime)) else str(d_val)
                w_rate = s.get("win_rate", 0.0)

                table_data.append([
                    Paragraph(d_str, self.style_td_bold),
                    Paragraph(str(s.get("number_of_users", 0)), self.style_td_right),
                    Paragraph(str(s.get("total_games", 0)), self.style_td_right),
                    Paragraph(str(s.get("games_won", 0)), self.style_td_right),
                    Paragraph(f"{w_rate:.1f}%", self.style_td_right),
                ])

            # Total Summary Row
            table_data.append([
                Paragraph("<b>Total / Average</b>", self.style_td_bold),
                Paragraph(f"<b>{tot_players}</b>", self.style_td_bold_right),
                Paragraph(f"<b>{tot_games}</b>", self.style_td_bold_right),
                Paragraph(f"<b>{tot_won}</b>", self.style_td_bold_right),
                Paragraph(f"<b>{win_rate:.1f}%</b>", self.style_td_bold_right),
            ])

            col_widths = [135, 95, 95, 100, 98]
            tbl = Table(table_data, colWidths=col_widths, repeatRows=1)

            # Table styling
            t_style = [
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#f1f5f9")),
                ("BOTTOMPADDING", (0, 0), (-1, 0), 6),
                ("TOPPADDING", (0, 0), (-1, 0), 6),
                ("LINEBELOW", (0, 0), (-1, 0), 1, colors.HexColor("#cbd5e1")),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("TOPPADDING", (0, 1), (-1, -1), 5),
                ("BOTTOMPADDING", (0, 1), (-1, -1), 5),
                ("LEFTPADDING", (0, 0), (-1, -1), 6),
                ("RIGHTPADDING", (0, 0), (-1, -1), 6),
                ("BOX", (0, 0), (-1, -1), 1, self.c_border),
                ("INNERGRID", (0, 0), (-1, -2), 0.5, colors.HexColor("#f1f5f9")),
                # Highlight Total Row
                ("BACKGROUND", (0, -1), (-1, -1), colors.HexColor("#f8fafc")),
                ("LINEABOVE", (0, -1), (-1, -1), 1, colors.HexColor("#cbd5e1")),
                ("TOPPADDING", (0, -1), (-1, -1), 6),
                ("BOTTOMPADDING", (0, -1), (-1, -1), 6),
            ]

            # Alternating rows
            for r_idx in range(1, len(table_data) - 1):
                if r_idx % 2 == 0:
                    t_style.append(("BACKGROUND", (0, r_idx), (-1, r_idx), self.c_bg_light))

            tbl.setStyle(TableStyle(t_style))
            elements.append(tbl)

        # Build PDF
        doc.build(elements, canvasmaker=NumberedCanvas)
        buffer.seek(0)
        return buffer

